 * العشرون ملفاتٍ مشتركة بمسؤولها ومشاركيها. يُبذر مرة واحدة: لا يعمل إن وُجد أي ملف (ولو محذوفاً)، فلا
 * يمس تعديلات الإدارة بعده.
 *
 * - النصوص حرفياً، ومنها التكرار في الدليل (12 و13 للمسؤول التنفيذي)، ولا ملف برقم 7 فيه (open-questions).
 * - «المالية» = المدير المالي والمحاسب، و«المشاريع» = مدير المشاريع، و«التسويق» = مدير التسويق، و«جميع
 *   الوظائف» = الست. و«أصحاب الاختصاص» و«المختص» لا يُترجمان إلى دور: يضيفهم المسؤول عن الملف.
 */
class JobFilesSeeder extends Seeder
