    private const MATRIX_SORT = 100;

    public function run(): void
    {
        if (JobFile::withTrashed()->exists()) {
            return;
        }

        DB::transaction(function (): void {
            foreach (self::jobLists() as $role => $files) {
                foreach ($files as $number => $line) {
                    [$title, $description] = array_map('trim', explode(':', $line, 2));
                    self::create(RoleName::from($role), $title, $description, [], $number, false);
                }
            }

            foreach (self::matrix() as $number => [$title, $responsible, $participants]) {
                self::create($responsible, $title, null, $participants, self::MATRIX_SORT + $number, true);
            }
        });
    }

    /**
     * @param  list<RoleName>  $participants
     */
    private static function create(RoleName $responsible, string $title, ?string $description, array $participants, int $sort, bool $fromMatrix): void
    {
        $file = new JobFile([
            'title' => $title,
            'description' => $description,
            'responsible_role' => $responsible,
            'participant_roles' => array_values(array_diff(RoleName::values($participants), [$responsible->value])),
            'participants_contribute' => false,
            'icon' => JobFileIcon::Folder,
            'sort' => $sort,
        ]);
        $file->from_matrix = $fromMatrix;
        $file->save();
    }

